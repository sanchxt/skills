// Regenerates the catalog half of KIT.md (between the <!-- catalog --> markers) from the code itself, so the list of
// components, caption styles, transitions, sounds, voice profiles, looks and sheets never goes stale.
//   pnpm kit:catalog            (also run by pnpm sync:reel)
// The hand-written half of KIT.md (how to choose, rules) is left alone.
import fs from "node:fs";
import path from "node:path";
import { ROOT } from "./paths.mjs";

const RS = process.env.REELSTUDIO_DIR ?? "D:/projects/SOCIAL MEDIA/short-form-quick-edits";
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const out = [];
const h = (s) => out.push(`\n### ${s}\n`);

// ---------- components: every export of every file reachable from the barrel ----------
h("Components (import from `../../components`)");
out.push("| File | Exports |\n|---|---|");
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]));
for (const f of walk(path.join(ROOT, "src/components")).filter((f) => /\.tsx?$/.test(f) && !f.endsWith("index.ts")).sort()) {
  const src = fs.readFileSync(f, "utf8");
  const names = [...src.matchAll(/^export (?:const|function|class) ([A-Za-z_][\w]*)/gm)].map((m) => m[1]);
  const types = [...src.matchAll(/^export type ([A-Za-z_][\w]*)/gm)].map((m) => m[1]);
  if (!names.length && !types.length) continue;
  const relf = path.relative(path.join(ROOT, "src/components"), f).replace(/\\/g, "/");
  out.push(`| \`${relf}\` | ${names.map((n) => `\`${n}\``).join(" ")}${types.length ? ` · types: ${types.join(", ")}` : ""} |`);
}

// ---------- caption styles ----------
h("Caption styles (`<Captions style=\"...\" />`)");
out.push("| id | look | best for |\n|---|---|---|");
for (const m of read("src/components/captions/Captions.tsx").matchAll(/\{ id: "([^"]+)", label: "([^"]+)", group: "Eravue", bestFor: "([^"]+)" \}/g)) out.push(`| \`${m[1]}\` | ${m[2]} | ${esc(m[3])} |`);
for (const m of read("src/vendor/reel/captions/presets.ts").matchAll(/^\tp\('([^']+)', '([^']+)', '([^']+)', '((?:[^'\\]|\\.)*)', '((?:[^'\\]|\\.)*)'/gm)) out.push(`| \`reel:${m[1]}\` | ${m[2]} (${m[3]}): ${esc(m[4])} | ${esc(m[5])} |`);

// ---------- transitions ----------
h("Transitions (`<Blend>` / `<Accent>` / `<Overlay>` by kind; `<TransitionSound>` for the matched sound)");
out.push("| id | kind | group | frames | sound | best for |\n|---|---|---|---|---|---|");
for (const m of read("src/vendor/reel/transitions/catalog.ts").matchAll(/p\(\{id: '([^']+)', label: '[^']*', group: '([^']+)', kind: '([^']+)', frames: (\d+),(?: pre: \d+,)? sound: (null|'[^']*')[^}]*?bestFor: '((?:[^'\\]|\\.)*)'/g)) {
  out.push(`| \`${m[1]}\` | ${m[3]} | ${m[2]} | ${m[4]} | ${m[5] === "null" ? "-" : m[5].replace(/'/g, "")} | ${esc(m[6])} |`);
}

// ---------- sounds ----------
h("Sounds (`<Sfx cues={[[frame, name, gain?]]} />`, files in public/sfx)");
const sfx = read("src/components/Sfx.tsx").match(/export type SfxName = ([^;]+);/)?.[1].match(/"(\w+)"/g)?.map((s) => s.replace(/"/g, "")) ?? [];
out.push(sfx.map((s) => `\`${s}\``).join(" · "));

// ---------- voice profiles ----------
h("Voice profiles (`pnpm voice:profile <slug> <media> --profile <id>`; shared with ReelStudio)");
const vpFile = fs.existsSync(path.join(RS, "brand/voice-profiles.json")) ? path.join(RS, "brand/voice-profiles.json") : path.join(ROOT, "src/vendor/brand/voice-profiles.json");
const vp = JSON.parse(fs.readFileSync(vpFile, "utf8"));
out.push("| id | settings | for |\n|---|---|---|");
out.push("| `default` | measured clean-up, no tone change (built in) | any recording |");
out.push("| `keep` | nothing but -16 LUFS levelling | audio already cleaned (e.g. in ReelStudio) |");
for (const p of vp.profiles ?? []) {
  const knobs = ["clarity", "warmth", "presence", "air"].filter((k) => p[k]).map((k) => `${k} ${p[k] > 0 ? "+" : ""}${p[k]}`).join(", ") || "no tone change";
  out.push(`| \`${p.id}\` | ${knobs} | ${esc(p.description)} |`);
}

// ---------- looks ----------
h("Looks (`src/looks/<id>.ts`, `pnpm new ... --look <id>`)");
for (const f of fs.readdirSync(path.join(ROOT, "src/looks")).filter((f) => !["index.ts", "types.ts"].includes(f))) {
  const s = read(`src/looks/${f}`);
  out.push(`- \`${f.replace(".ts", "")}\`: ${s.match(/name: "([^"]+)"/)?.[1] ?? ""}${/dark: true/.test(s) ? " (dark)" : ""}`);
}

// ---------- sheets ----------
h("Reference sheets (Remotion Studio or `pnpm stills <id> <frames>`)");
for (const m of read("src/Root.tsx").matchAll(/formats\("(\w+(?:Kit|Sheet))"/g)) out.push(`- \`${m[1]}-V\``);

const kit = path.join(ROOT, "KIT.md");
const doc = fs.readFileSync(kit, "utf8");
const a = "<!-- catalog:start (generated by pnpm kit:catalog; do not edit by hand) -->";
const b = "<!-- catalog:end -->";
if (!doc.includes(a) || !doc.includes(b)) throw new Error("KIT.md is missing the catalog markers");
fs.writeFileSync(kit, doc.slice(0, doc.indexOf(a) + a.length) + "\n" + out.join("\n") + "\n\n" + doc.slice(doc.indexOf(b)));
console.log(`KIT.md catalog: ${out.filter((l) => l.startsWith("| `")).length} rows`);
